<div class="content">
      <h2>System requirements</h2>

      <p> OS: Palm OS 3.5 or higher.  On Palm OS 5 devices with a 5-way
       navigator (Tungsten C and others) the navigator walks.<br>
       Memory: about 320 K for the game and kMoriaDB, plus room for your
       saved game.</p>
</div>

