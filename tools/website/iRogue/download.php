<div class="content">
      <h2>System requirements</h2>

      <p> OS: Palm OS 3.5 or higher.  On Palm OS 5 devices with a 5-way
       navigator (Tungsten C and others) you can play without the stylus.<br>
       Memory: about 130 K, plus about 10 K per save file, and 11 K for the
       tile set.</p>

      <p> iRogue creates its own database, iRogueDB (saved games and high
       scores), the first time it runs.</p>
</div>

